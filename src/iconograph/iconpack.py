"""iconpack.py — the `build` command: every installed app → the Iconograph theme.

    python -m iconograph build [--cores N] [--update] [--only GLOB]

Scans the installed-app census (appicons.installed_apps), resolves each icon
through the brand→Adwaita chain (appicons.resolve_icon), runs the stage 1→5
pipeline (application.pipeline.build_icon) and compiles the snakes into a
SELECTABLE freedesktop icon theme:

    ~/.local/share/icons/Iconograph/{index.theme, 24x24/apps/, 32x32/apps/}

Toggle ON:  gsettings set org.gnome.desktop.interface icon-theme 'Iconograph'
Toggle OFF: gsettings set org.gnome.desktop.interface icon-theme 'Adwaita'
(Inherits=Adwaita,hicolor — apps the pack doesn't cover keep their normal icon.)

INCREMENTAL by default (the manifest hash+skip rule — run it after installing a
new app; everything already built is skipped; the manifest flushes after every
app so an interrupted run resumes). `--update` reprocesses the ENTIRE set (the
explicit lever after pipeline code improvements). Icon file basenames are the
`.desktop` `Icon=` values VERBATIM (the theme-lookup contract). Deterministic
per app (H8): single-threaded workers, no RNG; the pool order only affects log
interleaving, never pixels.
"""
from __future__ import annotations

import fnmatch
import io
import contextlib
import multiprocessing as mp
import os
import subprocess
from pathlib import Path

import cv2
import numpy as np
from PIL import Image

from iconograph import manifest
from iconograph.appicons import AppEntry, IconSource, installed_apps, materialize, \
    resolve_icon, slug

REPO_ROOT = Path(__file__).resolve().parents[2]
ICONS_ROOT = Path.home() / ".local/share/icons"
STAGE_DIR = REPO_ROOT / ".cache" / "build" / "sources"
SIZES = (24, 32)

# TWO parallel themes from the SAME snake mask, differing only in fill: black
# glyphs for light desktops, white for dark (a black icon vanishes on a dark
# background). Light first — the default toggle target. The manifest lives with
# the light theme; each app's output paths are recorded relative to ICONS_ROOT
# (theme-name-prefixed) so ONE manifest entry tracks both themes' PNGs and the
# skip/prune logic resolves them under a single root.
LIGHT_DIR = ICONS_ROOT / "Iconograph"
DARK_DIR = ICONS_ROOT / "Iconograph-Dark"
PACK_DIR = LIGHT_DIR                       # manifest home (light == the primary theme)
THEMES: tuple[tuple[Path, str, tuple[int, int, int]], ...] = (
    (LIGHT_DIR, "Iconograph", (0, 0, 0)),
    (DARK_DIR, "Iconograph Dark", (255, 255, 255)),
)


def _index_theme(name: str) -> str:
    # 24/32 are Fixed rasters (the pixel-exact art at the small slots); scalable/apps
    # is the SVG upscale — MinSize=33 so it covers ONLY sizes above the rasters, where
    # the DE would otherwise bilinearly blur the 32px PNG. Size=48 is the nominal.
    return f"""[Icon Theme]
Name={name}
Comment=Abstract pixel logo + monogram icons generated by iconograph
Inherits=Adwaita,hicolor
Directories=24x24/apps,32x32/apps,scalable/apps

[24x24/apps]
Context=Applications
Size=24
Type=Fixed

[32x32/apps]
Context=Applications
Size=32
Type=Fixed

[scalable/apps]
Context=Applications
Size=48
MinSize=33
MaxSize=512
Type=Scalable
"""


def _snake_rgba(mask: np.ndarray, color: tuple[int, int, int] = (0, 0, 0)) -> np.ndarray:
    """(N,N) uint8 {0,255} snake → (N,N,4) `color`-on-TRANSPARENT RGBA. RGB is set
    on every pixel (not just the mask) so downscaling never fringes the glyph with
    the opposite tone."""
    n = mask.shape[0]
    rgba = np.zeros((n, n, 4), np.uint8)
    rgba[..., 0], rgba[..., 1], rgba[..., 2] = color
    rgba[..., 3] = (mask > 0).astype(np.uint8) * 255
    return rgba


def _snake_svg(mask: np.ndarray, color: tuple[int, int, int] = (0, 0, 0)) -> str:
    """(N,N) uint8 {0,255} snake → a scalable SVG of the pixel grid (one `<rect>`
    per horizontal ON-run), `color` fill on a transparent background. `viewBox` is
    the mask's own grid so a `Size=48 MinSize=33` scalable theme dir renders the
    EXACT pixel art crisply at any large size — `shape-rendering="crispEdges"` snaps
    edges to the device grid so even non-integer scales (e.g. 48 from a 32-grid) stay
    razor-sharp instead of the DE's bilinear blur. Deterministic (row-major, H8)."""
    n = mask.shape[0]
    on = mask > 0
    rects: list[str] = []
    for r in range(n):
        c = 0
        while c < n:
            if on[r, c]:
                c0 = c
                while c < n and on[r, c]:
                    c += 1
                rects.append(f'<rect x="{c0}" y="{r}" width="{c - c0}" height="1"/>')
            else:
                c += 1
    fill = "#%02x%02x%02x" % color
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {n} {n}" '
            f'shape-rendering="crispEdges" fill="{fill}">'
            + "".join(rects) + "</svg>\n")


def _worker_init() -> None:
    for v in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS"):
        os.environ.setdefault(v, "1")
    cv2.setNumThreads(1)


def _build_one(job: tuple) -> tuple:
    """Pool worker: ONE app end to end. Returns
    (lookup, status, outputs|reason, monogram, layouts, gate|None, log)."""
    lookup, entry, src = job
    from iconograph.application.pipeline import BuildError, build_icon
    buf = io.StringIO()
    try:
        staged = STAGE_DIR / f"{slug(lookup)}.png"
        materialize(src, staged)
        with contextlib.redirect_stdout(buf):
            built = build_icon(staged, entry.name)
        outputs = []
        for theme_dir, _name, fill in THEMES:
            for n in SIZES:
                rel = f"{theme_dir.name}/{n}x{n}/apps/{entry.icon}.png"
                dst = ICONS_ROOT / rel
                dst.parent.mkdir(parents=True, exist_ok=True)
                Image.fromarray(_snake_rgba(built.snakes[n], fill), "RGBA").save(
                    dst, "PNG", optimize=True)
                outputs.append(rel)
            # Scalable SVG (the upscale layer): the 32px master's pixel grid as
            # vector squares — crisp at every size > 32, no DE bilinear blur.
            svg_rel = f"{theme_dir.name}/scalable/apps/{entry.icon}.svg"
            svg_dst = ICONS_ROOT / svg_rel
            svg_dst.parent.mkdir(parents=True, exist_ok=True)
            svg_dst.write_text(_snake_svg(built.snakes[32], fill))
            outputs.append(svg_rel)
        gate = built.gate.as_dict() if built.gate is not None else None
        return (lookup, "built", outputs, built.monogram, built.layouts, gate,
                buf.getvalue())
    except BuildError as e:
        return (lookup, "failed", str(e), "", {}, None, buf.getvalue())
    except Exception as e:                                  # noqa: BLE001 — the batch
        return (lookup, "failed", f"{type(e).__name__}: {e}", "", {}, None,
                buf.getvalue())


def run_build(cores: int | None = None, update: bool = False,
              only: str | None = None) -> int:
    cores = cores or max(1, (os.cpu_count() or 2) // 2)
    os.environ["ICONOGRAPH_JOBS"] = str(cores)
    _worker_init()
    apps = installed_apps()
    man = manifest.load(PACK_DIR)
    for theme_dir, name, _fill in THEMES:
        theme_dir.mkdir(parents=True, exist_ok=True)
        idx, content = theme_dir / "index.theme", _index_theme(name)
        if not idx.exists() or idx.read_text() != content:
            idx.write_text(content)
    work: list[tuple] = []
    n_skip = n_unres = n_filtered = 0
    for lookup in sorted(apps):
        entry = apps[lookup]
        if only and not (fnmatch.fnmatch(lookup, only)
                         or fnmatch.fnmatch(entry.icon, only)):
            n_filtered += 1
            continue
        src = resolve_icon(entry.icon)
        if src is None:
            manifest.prune_outputs(man, ICONS_ROOT, lookup)  # was-built → unresolved
            manifest.record_unresolved(man, lookup, icon=entry.icon,
                                       name=entry.name)
            n_unres += 1
            continue
        if not update and manifest.should_skip(man, ICONS_ROOT, lookup, src.path):
            n_skip += 1
            continue
        work.append((lookup, entry, src))
    manifest.flush(PACK_DIR, man)
    print(f"iconograph build: {len(apps)} apps  ({len(work)} to build, "
          f"{n_skip} up-to-date, {n_unres} unresolved, {n_filtered} filtered)  "
          f"cores={cores}{'  [--update]' if update else ''}")
    n_built = n_fail = 0
    src_by_lookup = {j[0]: j[2] for j in work}
    entry_by_lookup = {j[0]: j[1] for j in work}
    if work:
        with mp.Pool(processes=min(cores, len(work)),
                     initializer=_worker_init) as pool:
            for res in pool.imap_unordered(_build_one, work):
                lookup, status, payload, mono, layouts, gate, _log = res
                entry, src = entry_by_lookup[lookup], src_by_lookup[lookup]
                if status == "built":
                    manifest.record_built(man, lookup, icon=entry.icon,
                                          name=entry.name, source=src.path,
                                          outputs=payload, gate=gate)
                    n_built += 1
                    flag = "  [color-suspect]" if gate and gate.get("suspect") else ""
                    print(f"  built  {lookup:<40} {mono}  "
                          f"{'/'.join(layouts.values())}{flag}")
                else:
                    manifest.prune_outputs(man, ICONS_ROOT, lookup)  # was-built → failed
                    manifest.record_failed(man, lookup, icon=entry.icon,
                                           name=entry.name, source=src.path,
                                           reason=payload)
                    n_fail += 1
                    print(f"  FAILED {lookup:<40} {payload}")
                manifest.flush(PACK_DIR, man)   # per-app: the resume contract
    for theme_dir, _name, _fill in THEMES:
        subprocess.run(["gtk-update-icon-cache", "-f", "-t", str(theme_dir)],
                       check=False, capture_output=True)   # best-effort (optional for GTK)
    print(f"done: {n_built} built, {n_skip} skipped, {n_fail} failed, "
          f"{n_unres} unresolved -> {LIGHT_DIR} (+ {DARK_DIR.name} for dark desktops)")
    if n_fail:
        print("failures (the curve-ball report):")
        for lookup, e in sorted(man.items()):
            if e.get("status") == "failed":
                print(f"  {lookup:<40} {e.get('reason')}")
    suspects = sorted((lk, e["gate"]) for lk, e in man.items()
                      if isinstance(e.get("gate"), dict) and e["gate"].get("suspect"))
    if suspects:
        print(f"categorization-suspect — interior color detail likely lost "
              f"pre-compression ({len(suspects)}; recommend color-difference):")
        for lk, g in suspects:
            print(f"  {lk:<40} collapse={g.get('collapse_kind')}:"
                  f"{g.get('collapse_iou')} marks={g.get('mark_frac')}")
        print("  (only apps built THIS run are re-evaluated; run "
              "`python -m iconograph.precompress_gate_debug` for the full picture)")
    return 0 if n_fail == 0 else 1
